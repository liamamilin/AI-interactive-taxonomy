#!/usr/bin/env python3
"""
AI-Interactive-Taxonomy 自动目录同步引擎
扫描 domains/<domain>/<topic>/ 并与 taxonomy.json 蓝图合并，
自动输出 catalog.json 与 catalog.js（供纯静态前端零构建加载）。
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TAXONOMY_PATH = ROOT / "taxonomy.json"
DOMAINS_DIR = ROOT / "domains"


def extract_html_meta(html_path: Path):
    text = html_path.read_text(encoding="utf-8", errors="ignore")
    title_m = re.search(r"<title>(.*?)</title>", text, re.S | re.I)
    h1_m = re.search(r"<h1[^>]*>(.*?)</h1>", text, re.S | re.I)
    raw_title = title_m.group(1).strip() if title_m else html_path.stem
    clean_title = re.sub(r"<[^>]+>", "", raw_title).split("·")[0].strip()
    clean_title = re.sub(r"^玩具\s*\d+\s*[:：]\s*", "", clean_title).strip()
    h1_text = re.sub(r"<[^>]+>", "", h1_m.group(1)).strip() if h1_m else clean_title
    return clean_title or html_path.stem, h1_text


def build_taxonomy_data():
    taxonomy = json.loads(TAXONOMY_PATH.read_text(encoding="utf-8"))
    domains_out = []
    total_topics = 0
    total_toys = 0
    lit_domains = 0

    for dom in sorted(taxonomy["domains"], key=lambda d: d["order"]):
        dom_id = dom["id"]
        dom_dir = DOMAINS_DIR / dom_id
        topics = []

        if dom_dir.exists() and dom_dir.is_dir():
            for topic_dir in sorted(dom_dir.iterdir()):
                if not topic_dir.is_dir() or topic_dir.name.startswith("."):
                    continue
                html_files = sorted(
                    f for f in topic_dir.glob("*.html") if f.name.lower() != "index.html"
                )
                if not html_files:
                    continue

                meta = {}
                meta_file = topic_dir / "meta.json"
                if meta_file.exists():
                    try:
                        meta = json.loads(meta_file.read_text(encoding="utf-8"))
                    except Exception:
                        meta = {}

                toys_meta = meta.get("toys", {})
                toys_list = []
                for hf in html_files:
                    p_title, p_h1 = extract_html_meta(hf)
                    tm = toys_meta.get(hf.name, {})
                    toys_list.append({
                        "id": f"{dom_id}/{topic_dir.name}/{hf.name}",
                        "file": hf.name,
                        "path": f"./domains/{dom_id}/{topic_dir.name}/{hf.name}",
                        "title": tm.get("title", p_title),
                        "icon": tm.get("icon", "🎮"),
                        "concept": tm.get("concept", "2 分钟互动原理"),
                        "summary": tm.get("summary", p_h1),
                    })

                default_branch = dom["branches"][0]["id"] if dom.get("branches") else "general"
                topics.append({
                    "id": f"{dom_id}/{topic_dir.name}",
                    "slug": topic_dir.name,
                    "domain": dom_id,
                    "branch": meta.get("branch", default_branch),
                    "order": meta.get("order", 999),
                    "title": meta.get("title", topic_dir.name.replace("-", " ").title()),
                    "icon": meta.get("icon", dom["icon"]),
                    "color": meta.get("color", dom["color"]),
                    "soft": meta.get("soft", dom["soft"]),
                    "subtitle": meta.get("subtitle", "2 分钟交互式科普原型集合"),
                    "difficulty": meta.get("difficulty", "入门"),
                    "related": meta.get("related", []),
                    "toys": toys_list,
                })

        topics.sort(key=lambda t: (t["order"], t["slug"]))
        if topics:
            lit_domains += 1
        total_topics += len(topics)
        dom_toy_count = sum(len(t["toys"]) for t in topics)
        total_toys += dom_toy_count

        domains_out.append({
            **dom,
            "liveTopicCount": len(topics),
            "liveToyCount": dom_toy_count,
            "topics": topics,
        })

    return {
        "version": taxonomy.get("version", "1.0.0"),
        "title": taxonomy.get("title", "AI-Interactive-Taxonomy"),
        "subtitle": taxonomy.get("subtitle", ""),
        "stats": {
            "totalDomains": len(domains_out),
            "litDomains": lit_domains,
            "totalTopics": total_topics,
            "totalToys": total_toys,
        },
        "rings": taxonomy.get("rings", []),
        "domains": domains_out,
    }


def main():
    data = build_taxonomy_data()
    json_str = json.dumps(data, ensure_ascii=False, indent=2)

    (ROOT / "catalog.json").write_text(json_str + "\n", encoding="utf-8")
    (ROOT / "catalog.js").write_text(
        "// Auto-generated by scripts/sync_catalog.py — 请勿手改，新增主题后运行同步脚本即可\n"
        f"window.TAXONOMY_DATA = {json_str};\n",
        encoding="utf-8",
    )
    st = data["stats"]
    print(
        f"✅ Taxonomy 同步完成：已点亮 {st['litDomains']}/{st['totalDomains']} 大领域，"
        f"共 {st['totalTopics']} 个主题、{st['totalToys']} 个互动玩具 -> catalog.js"
    )


if __name__ == "__main__":
    main()
